"""(A) Audit agent - runs at the END of a round (all units completed, human feedback done). Report only.

Every authored change in the run is checked and attributed to its author:
  LLM     llm_applied     A) conversions the LLM agent applied
  Human   user_applied    corrections keyed in the UI
  Repair  repair_applied  related-set swaps by the repair agent

Checks (each recorded, passes included, so the UI can show counts per author):
  rule      the authored value, placed into the unit's FINAL draft, against field + count rules
            (a value superseded by ANOTHER author that would break a rule = that author broke it, the other
            fixed it). An author's own intermediate values - later overwritten by the same author - are
            not judged: only each author's last value per cell counts. Violations on OTHER cells that got
            their final value after the change (a later change by anyone, or regenerated by a later re-run
            from their level or below) are not charged to it - they did not exist when it was made.
  feedback  the change used a pair the user weighted -1 ("never") in LLMfeedback.json
  unit      repair swaps: the unit's final draft passes every rule
Nothing is reverted or changed in the drafts.
"""
from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path
from typing import Any

from . import ROOT  # noqa: F401  (sets sys.path)
import formats  # noqa: E402
import generator  # noqa: E402
from source import load_db_formats  # noqa: E402
import weights as fb_weights  # noqa: E402
from schema import build_plan  # noqa: E402
from settings import Config  # noqa: E402

AUTHORS = (("LLM", "llm_applied"), ("Human", "user_applied"), ("Repair", "repair_applied"))


def _cell(draft: dict[str, Any], table: str, record: int | None) -> dict[str, Any] | None:
    rows = draft.get(table)
    if record is None:
        return rows if isinstance(rows, dict) else None
    return rows[record] if isinstance(rows, list) and 0 <= record < len(rows) else None


def _relevant(v: dict[str, Any], table: str, record: int | None, field: str) -> bool:
    if v["table"] != table or v["field"] != field:
        return False
    if v.get("kind") == "count":
        return record is None or record in (v.get("records") or []) or v.get("count", 0) > v["allowed_count"][1]
    return v.get("record") == record


def _why(viol: list[dict[str, Any]]) -> str:
    """'Table.Field[rec]: reason' per violation, de-duplicated."""
    out = []
    for v in viol:
        rec = "" if v.get("record") is None else f"[{v['record']}]"
        txt = f"{v['table']}.{v['field']}{rec}: {v['reason']}"
        if txt not in out:
            out.append(txt)
    return "; ".join(out[:3]) + (" ..." if len(out) > 3 else "")


def _own_intermediate(changes: list[dict[str, Any]], dbf: dict[str, str]) -> set[int]:
    """Indices of changes the SAME author later overwrote on the same cell (chained on the value, so stale
    record indices after deletions don't mix cells). Older run files kept these; they are not audited."""
    skip = set()
    for i, a in enumerate(changes):
        for b in changes[i + 1:]:
            if (a["table"], a.get("record"), a["field"]) != (b["table"], b.get("record"), b["field"]):
                continue
            to_db = formats.convert(a.get("to"), dbf.get(f"{a['table']}.{a['field']}"))
            if generator.same(b.get("from"), a.get("to")) or generator.same(b.get("from"), to_db):
                skip.add(i)
                break
    return skip


def _vkey(v: dict[str, Any]) -> tuple:
    return (v.get("kind"), v["table"], v["field"], v.get("record"), str(v.get("value")), v.get("reason"))


def _later_values(u: dict[str, Any], level_of: dict[tuple[str, str], int]):
    """rederived(v, attempt): the cell(s) of violation v got their final value AFTER that attempt - changed by
    any author later, or regenerated by a later re-run that started at or below the field's level."""
    reruns = [(int(m.group(1)), int(m.group(2))) for n in u.get("notes", [])
              for m in [re.match(r"re-run #(\d+) from level (\d+)", str(n))] if m]
    changes = [(c["table"], c.get("record"), c["field"], int(c.get("attempt") or 0))
               for c in (u.get("llm_applied") or []) + (u.get("user_applied") or [])]
    swaps = [(set(c.get("records") or {}), int(c.get("attempt") or 0)) for c in u.get("repair_applied") or []]

    def rederived(v: dict[str, Any], after: int) -> bool:
        t, f = v["table"], v["field"]
        lvl = level_of.get((t, f))
        if lvl is not None and any(b > after and start <= lvl for b, start in reruns):
            return True
        if any(t in tables and a > after for tables, a in swaps):
            return True
        return any(ct == t and cf == f and a > after and (v.get("kind") == "count" or cr == v.get("record"))
                   for ct, cr, cf, a in changes)
    return rederived


def audit_run(run_path: Path | str, cfg: Config, round_no: int) -> dict[str, Any]:
    path = Path(run_path)
    data = json.loads(path.read_text(encoding="utf-8"))
    plan, registry = build_plan(cfg), generator.load_rules()
    full = len(plan.levels)
    dbf = load_db_formats(cfg)  # authored values are stored converted to the DB type
    try:
        fb = fb_weights._feedback_module()
        blocked, norm = fb.blocked_values(), fb.norm
    except Exception:
        blocked, norm = set(), str
    findings: list[dict[str, Any]] = []

    def add(u, author, ch, check, verdict, detail):
        findings.append({"unit_id": u["unit_id"], "key": u["key"], "author": author,
                         "table": ch.get("table", ""), "record": ch.get("record"), "field": ch.get("field", ""),
                         "from": ch.get("from"), "to": ch.get("to"), "check": check, "verdict": verdict,
                         "detail": detail})

    level_of = {(t, f): i for i, nodes in enumerate(plan.levels) for t, f in nodes}
    for u in data["units"]:
        final = u["draft"]
        baseline = {_vkey(v) for v in generator.check_all(registry, cfg, plan, final, full)}
        rederived = _later_values(u, level_of)
        for author, key in AUTHORS:
            changes = u.get(key) or []
            own = _own_intermediate(changes, dbf) if author != "Repair" else set()
            for n, ch in enumerate(changes):
                if n in own:
                    continue  # the author's own intermediate value, overwritten by themselves - not tracked
                if author == "Repair":
                    rec = {"table": ", ".join(ch.get("records", {})), "from": f"unit {ch.get('from_unit')}",
                           "to": f"unit {ch.get('to_unit')}"}
                    if u["status"] != "completed":
                        add(u, author, rec, "unit", "pending", "unit still halted - judged once it completes")
                    else:
                        viol = generator.check_all(registry, cfg, plan, final, full)
                        add(u, author, rec, "unit", "violation" if viol else "ok",
                            _why(viol) or "final draft passes every rule")
                    continue
                t, r, f = ch["table"], ch.get("record"), ch["field"]
                row = _cell(final, t, r)
                if row is None:
                    add(u, author, ch, "rule", "skipped", "record no longer exists (deleted or re-keyed)")
                else:
                    trial = json.loads(json.dumps(final))
                    _cell(trial, t, r)[f] = ch["to"]
                    # violations this value causes: new ones vs the final draft (also via conditions, e.g. a
                    # parent change that breaks a child count rule) + any on the changed cell itself
                    viol = [v for v in generator.check_all(registry, cfg, plan, trial, full)
                            if _vkey(v) not in baseline or _relevant(v, t, r, f)]
                    # other cells whose final value came after this change are no evidence against it
                    after = int(ch.get("attempt") or 0)
                    later = [v for v in viol if not _relevant(v, t, r, f) and rederived(v, after)]
                    viol = [v for v in viol if v not in later]
                    to_db = formats.convert(ch["to"], dbf.get(f"{t}.{f}"))
                    kept = generator.same(row.get(f), ch["to"]) or generator.same(row.get(f), to_db)
                    if viol:
                        add(u, author, ch, "rule", "violation",
                            _why(viol)
                            + ("" if kept else f" (later changed to {row.get(f)!r})"))
                    else:
                        skipped = sorted({f"{v['table']}.{v['field']}" for v in later})
                        add(u, author, ch, "rule", "ok", ("kept in final draft" if kept
                                                          else f"valid, but later changed to {row.get(f)!r}")
                            + (f" ({', '.join(skipped)} got its value after this change - not judged)"
                               if skipped else ""))
                if (t, f, norm(ch.get("from")), str(ch["to"])) in blocked:
                    add(u, author, ch, "feedback", "violation",
                        f"{ch.get('from')!r} -> {ch['to']!r} is weighted -1 (never) in LLMfeedback.json")
    by_author = {a: {"checks": sum(1 for x in findings if x["author"] == a),
                     "violations": sum(1 for x in findings if x["author"] == a and x["verdict"] == "violation")}
                 for a, _ in AUTHORS}
    report = {"round": round_no, "at": datetime.now().isoformat(timespec="seconds"),
              "summary": by_author, "findings": findings}
    data = json.loads(path.read_text(encoding="utf-8"))
    data["audit"] = report
    path.write_text(json.dumps(data, indent=2, default=str), encoding="utf-8")
    return report
